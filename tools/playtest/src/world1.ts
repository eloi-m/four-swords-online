const CAVE = "boss011", TOWER = "boss012", CASTLE = "boss013";

/** Switch `n` of the room the Links are in. */
const sw = (n: number) => (g: AdventureGame) => ((g.battle.switches >>> n) & 1) === 1;
/** Switch `n` of room `room`, the Links in it or not. */
const swIn = (room: number, n: number) => (g: AdventureGame) => ((g.adventure.room === room ? g.battle.switches : savedSwitches(g, room)) >>> n & 1) === 1;
const inRoom = (room: number, area = 0) => (g: AdventureGame) => g.adventure.room === room && g.adventure.area === area && !g.adventure.warp;
const leaderX = (g: AdventureGame) => g.players[0]!.x / SUBPX;
const leaderY = (g: AdventureGame) => g.players[0]!.y / SUBPX;
/** A swim to an off spot (Tingle's Tower's rivers). */
const swimTo = (x: number, y: number): Goal => travelTo(x, y, { swim: true, tol: 0.75, exact: true });

